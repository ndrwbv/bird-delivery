import assert from 'node:assert/strict';
import {ShapeUtils,Vector2} from '../src/vendor/three.module.min.js';
globalThis.location={search:'?raisedland'};
const L=await import('../src/game/raisedland.js');
assert.throws(()=>L.activate(),/ещё не готова/,'Незавершённый контур не становится опорой');
L.record(16,0,32,0,16,32,.1,180,175,170);
assert.equal(L.onLand(4,4),false);
const triangulate=(outer,holes)=>({points:[...outer,...holes.flat()],triangles:ShapeUtils.triangulateShape(outer.map(p=>new Vector2(...p)),holes.map(h=>h.map(p=>new Vector2(...p))))});
L.finalMask.add([0,0,32,32],[{outer:[[0,0],[16,0],[16,32],[0,32]],holes:[]}],triangulate);L.finalMask.finish();
L.activate((x,z)=>x<0||z<0);
assert.equal(L.ST.built,false,'Готовая опора не объявляет рисунок завершённым');assert.equal(L.ST.supportReady,true);
assert.equal(L.onLand(4,4),true);assert.equal(L.onLand(24,4),false);assert.equal(L.onLand(-4,4),false,'Вне карты грунт не поднимается');
assert.equal(L.offset(4,4,20),.46);assert.equal(L.offset(24,4,20),0);
const count=L.cover.count;L.record(0,0,3,0,0,3,.1,180,175,170);assert.equal(L.cover.count,count,'Сезонные вещи не меняют уже готовый контур');
const g={p:new Float32Array([4,1,4]),landAnchor:[4,4]},item={x:4,z:4,v0:0,nv:1,mesh:{geometry:{attributes:{position:{array:new Float32Array([4,1,4]),addUpdateRange(){}}}}}},prop={x:4,z:4,pivot:{position:{y:1}}},bench={x:4,z:4,y:1};
L.alignObjects({lists:[[g]],items:[item],props:[prop],benches:[bench],baseH:()=>20});
assert.ok(Math.abs(g.p[1]-1.46)<1e-6);assert.ok(Math.abs(item.mesh.geometry.attributes.position.array[1]-1.46)<1e-6);assert.equal(prop.pivot.position.y,1.46);assert.equal(bench.y,1.46);
assert.equal(g.landAnchor,undefined,'Источник вещи готов к единственной окончательной склейке');
console.log('landready: опора после полного контура, прежние высоты вещей до склейки, запрет новых покрытий и отдельная готовность рисунка — OK');
