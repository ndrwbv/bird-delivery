import assert from 'node:assert/strict';
import {cleanLandPolygons,landCleanTile,landWidth} from '../src/game/landclean.js';
import {createLandCover} from '../src/game/landcover.js';
const rect=(x0,z0,x1,z1)=>[[x0,z0],[x1,z0],[x1,z1],[x0,z1]];
const inside=(p,x,z)=>{let hit=false;for(let i=0,j=p.length-1;i<p.length;j=i++){const a=p[i],b=p[j];if((a[1]>z)!==(b[1]>z)&&x<(b[0]-a[0])*(z-a[1])/(b[1]-a[1])+a[0])hit=!hit;}return hit;};
const filled=(patches,x,z)=>patches.some(p=>inside(p.outer,x,z)&&!p.holes.some(h=>inside(h,x,z)));
const small=cleanLandPolygons([rect(-5,-.15,5,.15)],[-4,-1,4,1]);
for(let x=-3.9;x<4;x+=.2)assert.ok(filled(small,x,0),'Тонкая полоска уходит в покрытие');
const wide=cleanLandPolygons([rect(-5,-1,5,1)],[-4,-2,4,2]);
for(let x=-3.9;x<4;x+=.2)assert.ok(!filled(wide,x,0),'Широкая земля сохраняется');
const ring=cleanLandPolygons([rect(-1,-1,1,1),rect(-.8,-.8,.8,.8).reverse()],[-2,-2,2,2]);
assert.ok(filled(ring,.9,0),'Тонкое кольцо уходит в покрытие');
assert.ok(!filled(ring,0,0),'Отверстие не заполняется повторным полом');
const joined=[[-4,-2],[0,-2],[0,-.1],[5,-.1],[5,.1],[0,.1],[0,2],[-4,2]];
const trimmed=cleanLandPolygons([joined],[-3,-3,6,3]);
assert.ok(filled(trimmed,3,0),'Тонкий отросток удалён');assert.ok(!filled(trimmed,-2,0),'Основной газон сохранён');
const shapes=[rect(-8,-.15,8,.15),rect(-8,-3,-1.5,3)];
const all=cleanLandPolygons(shapes,[-4,-4,4,4]);
const halves=[...cleanLandPolygons(shapes,[-4,-4,0,4]),...cleanLandPolygons(shapes,[0,-4,4,4])];
for(let x=-3.95;x<4;x+=.1)for(let z=-.25;z<.3;z+=.05)assert.equal(filled(halves,x,z),filled(all,x,z),'Общая граница клеток не меняет форму');
const c=createLandCover(),g=createLandCover();
const pave=(x0,z0,x1,z1)=>{const p=rect(x0,z0,x1,z1);c.triangle(...p[0],...p[1],...p[3],.1);c.triangle(...p[2],...p[3],...p[1],.1);};
pave(-10,-10,0,10);pave(.2,-10,10,10);
const gap=landCleanTile(c,g,[-2,-2,2,2]);assert.ok(filled(gap,.1,0),'Узкий остаток между двумя покрытиями убран');
assert.ok(Math.abs(landWidth(c,g,{a:[0,1],b:[0,-1]})-.2)<1e-6,'Поперечный луч измеряет настоящую ширину остатка');
const empty=landCleanTile(createLandCover(),g,[-2,-2,2,2]);assert.equal(empty.length,0,'Открытое поле не меняется');
const floor=createLandCover(),islands=createLandCover();
const addRect=(cover,p,h)=>{cover.triangle(...p[0],...p[1],...p[3],h);cover.triangle(...p[2],...p[3],...p[1],h);};
addRect(floor,rect(-10,-10,10,10),.1);addRect(floor,rect(-.5,-1,.5,1),.2);
addRect(islands,rect(-2,-.15,2,.15),.15);
const levels=landCleanTile(floor,islands,[-3,-2,3,2]);
assert.ok(filled(levels,-1,0),'Тонкий остров поверх низкого мощения удаляется');
assert.ok(!filled(levels,0,0),'Высокое мощение остаётся поверх зелёного слоя');
console.log('landclean: узкие полоски и отростки удаляются; широкая земля, отверстия и стыки клеток сохраняются');
