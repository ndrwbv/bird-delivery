import assert from 'node:assert/strict';
import fs from 'node:fs';
const AsyncFunction=Object.getPrototypeOf(async function(){}).constructor;
const check=new AsyncFunction('d','until','wait',fs.readFileSync(new URL('./probe-checks/raised-land-joins.js',import.meta.url),'utf8'));
const section=(ax,az,bx,bz,h=1)=>[ax,az-.12,h,ax,az,h,bx,bz-.12,h,bx,bz,h,(ax+bx)/2,(az+bz)/2,ax,az,bx,bz];
const trace=[...section(0,0,1,0),...section(1,0,2,0),...section(1.01,.01,3,.01)];
const run=async(T,Q,wall=(x,z)=>x===0||x===2||z>.005,feet=[])=>check({CURBS:{trace:T,traceTopology:Q,api:{inHouse:wall,inBounds:()=>true}},RLAND:{ST:{built:true},cover:{inBox:()=>feet}},RLAND_BASE:()=>1,LATE:{busy:()=>false},crashlog:{count:()=>0}},async f=>f(),async()=>{});
const links={links:[0,1],bridges:[],open:[0,0,1,1,2,0,2,1]};
assert.equal((await run(trace,links)).ok,true,'Проверяются реальные соседи; близкий посторонний торец не подменяет стык');
const gap=trace.slice();gap[18]+=.04;assert.equal((await run(gap,links)).gap,1,'Щель 4 см между настоящими соседями выявляется');
const step=trace.slice();step[20]+=.04;assert.equal((await run(step,links)).step,1,'Ступенька 4 см между настоящими соседями выявляется');
assert.equal((await run(trace,links,x=>x!==3)).unmatched,1,'Открытый торец внутри города не пропускается');
assert.ok((await run(trace,{...links,open:[]})).untracked>0,'Секция без сведений о её конце не пропускается');
const feet=[[0,0],[2,0],[1.01,.01],[3,.01]].map(([x,z])=>({p:[[x-.05,z-.05],[x+.05,z-.05],[x,z+.05]],lift:.5}));
assert.equal((await run(trace,links,()=>false,feet)).ok,true,'Торец у точной грани здания распознаётся при пропуске пространственной сетки');
assert.ok((await run(trace,links,()=>false,feet.map(t=>({...t,rgb:[120,120,120]})))).unmatched>0,'Обычное высокое покрытие не выдаётся за стену');
const bridgeTrace=[...section(0,0,1,0),...section(1,0,1,1)];
bridgeTrace[18]=1.12;bridgeTrace[19]=0;
const bridge={links:[],bridges:[0,1,1,0,1,-.12,1.12,0,1],open:[0,0,1,1]};
const result=await run(bridgeTrace,bridge,(x,z)=>x===0||z===1);
assert.equal(result.bridges,1);assert.equal(result.ok,true,'Фаска примыкает к обоим фактическим торцам');
bridge.bridges[4]+=.04;assert.ok((await run(bridgeTrace,bridge)).gap>0,'Оторванная от торца фаска выявляется');
console.log('landcurb trace: реальные связи, посторонние близкие торцы, щель, ступенька, открытый конец и фаска — OK');
