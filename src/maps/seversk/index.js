const SE_Z = 1280;
function inPoly (x, z, p) {
  let c = false;
  for (let i = 0, j = p.length - 1; i < p.length; j = i++) {
    const [ax, az] = p[i], [bx, bz] = p[j];
    if ((az > z) !== (bz > z) && x < (bx - ax) * (z - az) / (bz - az) + ax) c = !c;
  }
  return c;
}
function districtAt (x, z) {
  if (x < -1380) return 7;                           // частный сектор на западе
  const side = RLU[0] * (z - RL0[1]) - RLU[1] * (x - RL0[0]);
  if (z < -1250 || (side < 0 && z < 150)) return 6;  // север: гаражи и заводы
  if (side < 0) return z > SE_Z ? 0 : 5;             // восток: особняки, промка; южнее SE_Z — Юг до выезда на Томск
  if (z > 1270 && inPoly(x, z, SOUTH)) return 0;     // Юг: южнее Солнечной и Коммунистического
  const t = (x - P0[0]) * AX[0] + (z - P0[1]) * AX[1];
  for (let i = 0; i < BANDS.length; i++) if (t < BANDS[i]) return i;
  return 4;
}
