const pool = () => HEROES.filter(h => !h.adult || (A && A.ADULT));
/* кого можно сейчас: пол клиента, не исчерпан, не был последние EVERY смен, папа — после всех детей */
function candidates (fem, n, sv) {
  const P = sv.p;
  return pool().filter(h => {
    if ((h.sex === 'f') !== !!fem) return false;
    const r = P[h.id] || { step: 0, last: -99 };
    if (r.last > n) r.last = -99;                       // прогресс сбросили — старые отметки не держат
    if (r.step >= h.meets.length) return false;
    if (n - r.last < REG.EVERY) return false;
    if (h.papa && !KIDS.every(k => (P[k] && P[k].step > 0))) return false;
    return true;
  });
}
/* все сыграны — круг заново (кроме тех, кто был недавно) */
function wrap (sv) {
  if (pool().every(h => (sv.p[h.id] && sv.p[h.id].step >= h.meets.length))) {
    for (const k in sv.p) sv.p[k].step = 0;
  }
}

/** вручение (oddfolk.js onHand): кто из героев — или ''. ctx: { shift, gapOk, sceneShift, fem } */
export function roll (st, onTime, o, ctx) {
  if (!A || !A.CAREER || !o || !o.ord) return '';
  const p = st && st.peds && st.peds[0];
  if (!p || !st.persons || !st.persons[0]) return '';
  const fem = !!(p.grp && p.grp.userData && p.grp.userData.fem);
  const n = ctx.shift, sv = load();
  ST.rolls++;
  if (force && BY[force]) {
    const f = force;
    if (BY[f].adult && !A.ADULT) return '';                          // пол — любой: клиент у двери всё равно станет героем (play)
    force = '';
    return pick(f, n, sv);
  }
  const no = n <= REG.FROM_SHIFT ? 'первая смена' : sv.shift === n ? 'герой уже был в смене' : ctx.sceneShift ? 'в смене была сценка'
    : !ctx.gapOk ? 'мало вручений после встречи' : '';
  if (no) { ST.skip[no] = (ST.skip[no] || 0) + 1; return ''; }
  if (Math.random() >= REG.P) return '';
  wrap(sv);
  const c = candidates(fem, n, sv);
  if (!c.length) { ST.skip['некого'] = (ST.skip['некого'] || 0) + 1; return ''; }
  if (!ctx.dirOk()) { ST.skip['режиссёр'] = (ST.skip['режиссёр'] || 0) + 1; return ''; }
  // начатые истории — чуть чаще новых: продолжение не теряется
  const w = c.map(h => ((sv.p[h.id] && sv.p[h.id].step) ? 1.6 : 1));
  let x = Math.random() * w.reduce((a, b) => a + b, 0), k = 0;
  while (k < c.length - 1 && (x -= w[k]) > 0) k++;
  return pick(c[k].id, n, sv);
}
function pick (id, n, sv) {
  const h = BY[id], r = sv.p[id] || { step: 0, last: -99 };
  if (r.step >= h.meets.length) r.step = 0;
  const step = r.step;
  r.step++; r.last = n;
  sv.p[id] = r; sv.shift = n;
  save(sv);
  ST.by[id] = (ST.by[id] || 0) + 1;
  return id + ':' + step;
}
