function load () {
  let v = null;
  try { v = A && A.Store ? A.Store.get(KEY, null) : null; } catch (e) { v = null; }
  if (typeof v === 'string') { try { v = JSON.parse(v); } catch (e) { v = null; } }
  return v && typeof v === 'object' && v.p ? v : { p: {}, shift: -1 };
}
