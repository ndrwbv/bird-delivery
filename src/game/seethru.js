/* ──────────────────────────────────────────────────────────────────────────
   Деревья, кусты и столбы между камерой и машиной тают (0п47, 24.10.2026; находка: «в виде „сзади“ ствол и ветки
   зимнего дерева встают между камерой и машиной — машину не видно»). Правила словами — docs/CAREER.md
   «Камера: три вида» → «Деревья, кусты и столбы между камерой и машиной тают».

   Как: в шейдере склеек деревьев (seasons.js PILE: ствол, ветки, крона, кусты под окнами, ёлки), сбиваемого (SMASH:
   столбы фонарей, знаки, заборчики, дворовые кусты) и ельника (forest.js). Конус от камеры до машины (вершина — в
   камере, у машины радиус SEE.R — сама машина с запасом): всё, что внутри, тает узором 4 × 4 (как растворение вдали,
   fade.js) — остаётся каждая четвёртая точка, сквозь ствол видно машину. Край конуса мягкий. Ни прозрачности, ни
   сортировки, ни новых отрисовок; дома не тают (камера у стены подходит ближе — game.js camStep).

     SEE_U          — юниформа (общая для всех трёх материалов): точка машины xyz и сила w
     SEE_FN         — функция seeCut(мировая точка) для фрагментного шейдера (bayer4 — из fade.js, подключать рядом)
     step(dt, x, y, z, on) — каждый кадр после камеры: где машина, включено ли (сзади — да, из-за руля и в меню — нет)
   ────────────────────────────────────────────────────────────────────────── */
export const SEE = {
  R: 2.8,        // м — радиус конуса у машины (полудлина машины 2,25 + запас на крышу)
  R0: 0.3,       // м — не уже у самой камеры (ветка перед объективом)
  EDGE: 0.6,     // доля радиуса: ближе к оси — тает полностью, к краю — мягко
  END: 2.6,      // м — у самой машины (ближе к ней по лучу) не тает: то, что рядом с машиной, видно
  LOW: 0.6,      // м — ниже точки машины на столько (≈ 0,2 м над землёй) не тает: листва и сугробы на земле
  MAX: 0.75,     // сколько точек узора пропадает в середине конуса: 0,75 — остаётся каждая четвёртая
  LENS: [1.2, 3],  // м от камеры: ближе 1,2 — ветки и листва пропадают целиком (камера в кроне), к 3 м — тают
  MINL: 3.5,     // м — камера ближе к машине (из-за руля) — ничего не тает
  UP: 0.8,       // м — точка машины над её низом (середина кузова)
  K: 6,          // как быстро включается / выключается (1/с)
};
export const SEE_U = { value: [0, -9999, 0, 0] };
const OFF = typeof location !== 'undefined' && new URLSearchParams(location.search).has('oldsee');

const f = v => v.toFixed(2);
export const SEE_FN = `
uniform vec4 uSeeP;
float seeK (vec3 wp) {
  if (uSeeP.w <= 0.001) return 0.0;
  vec3 d = uSeeP.xyz - cameraPosition;
  float L = length(d);
  if (L < ${f(SEE.MINL)}) return 0.0;
  vec3 dir = d / L, r = wp - cameraPosition;
  float t = dot(r, dir), tEnd = L - ${f(SEE.END)};
  if (t <= 0.0 || t >= tEnd || wp.y < uSeeP.y - ${f(SEE.LOW)}) return 0.0;
  float rad = max(${f(SEE.R0)}, ${f(SEE.R)} * t / L);
  float q = length(r - dir * t);
  return (1.0 - smoothstep(rad * ${f(SEE.EDGE)}, rad, q)) * smoothstep(tEnd, tEnd - 1.5, t) * uSeeP.w;
}
/* у самого объектива (камера въехала в крону) — ближе LENS[0] м пропадает целиком, к LENS[1] — тает */
float seeLens (vec3 wp) {
  if (uSeeP.w <= 0.001 || length(uSeeP.xyz - cameraPosition) < ${f(SEE.MINL)}) return 0.0;
  return (1.0 - smoothstep(${f(SEE.LENS[0])}, ${f(SEE.LENS[1])}, length(wp - cameraPosition))) * uSeeP.w;
}
void seeCut (vec3 wp) { if (max(seeK(wp) * ${f(SEE.MAX)}, seeLens(wp)) > bayer4(gl_FragCoord.xy)) discard; }`;

export const ST = { w: 0, off: false };            // off — выключить на ходу (проверка «до / после»: __dlv.SEE.off)
/** каждый кадр после камеры: (x, y, z) — низ машины игрока, on — тает ли (виды «сзади») */
export function step (dt, x, y, z, on) {
  const v = SEE_U.value;
  const w = v[3] + ((on && !OFF && !ST.off ? 1 : 0) - v[3]) * (1 - Math.exp(-SEE.K * (dt || 0)));
  v[0] = x; v[1] = y + SEE.UP; v[2] = z; v[3] = w < 0.002 ? 0 : w;
  ST.w = v[3];
}
