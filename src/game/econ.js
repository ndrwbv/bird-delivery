export const BREAK = {
  KM_WEAR: 0.4,                // % мотора за км × wearK (смена — ~8—13 км)
  HIT_WEAR: vn => Math.max(0.2, Math.min(1.5, 0.2 + (vn - 10) * 0.05)),   // % за удар (vn — сила, м/с) × wearK
  GANG_WEAR: 10,               // бандиты помяли — мотор −10 %
  CEIL_PER_KM: 0.07,           // % ресурса за км × wearK
  CEIL_DROP_MIN: 4, CEIL_DROP_PER: 0.08, CEIL_DROP_MAX: 8,   // ресурс за один ремонт
  CEIL_MIN: 20,                // ниже ресурс не падает
  GRACE_KM: 30,                // обкатка новой машины: столько км (~3 смены) не глохнет
  STALL: [[100, 0], [70, 0], [60, 0.05], [50, 0.125], [35, 0.3], [20, 0.5], [0, 0.75]],
  POTHOLE: 0.25,               // яма: шанс заказа × 0,25
  REPAIR_BASE: 1500, REPAIR_PER_PCT: 150,
  REPAIR_MIN_PCT: 1,           // восстанавливать меньше 1 % — «нечего крутить»
  MINIGAME_HITS: 3,            // сколько раз попасть по зелёному — всего, не подряд: промах не в счёт
  FROM_SHIFT: 5,               // ломается (глохнет) только с 5-й смены карьеры
  MINIGAME_ZONE: w => Math.max(0.1, 0.26 - w * 0.015),   // ширина зелёного; w = (100 − мотор) / 10
  OLD_L: L => Math.max(20, Math.min(95, 95 - 10 * L)),   // старое сохранение: ломучесть L → мотор %
};
export const wearK = car => 0.4 + 0.2 * (car && isFinite(+car.L) ? +car.L : 3);
/* шанс заглохнуть за заказ при моторе c % */
export function stallChance (c) {
  const T = BREAK.STALL;
  if (!(c < T[0][0])) return T[0][1];
  for (let i = 1; i < T.length; i++) {
    const [c1, p1] = T[i - 1], [c2, p2] = T[i];
    if (c >= c2) return p1 + (p2 - p1) * (c1 - c) / (c1 - c2);
  }
  return T[T.length - 1][1];
}
/* ремонт у Дяди Жени: мотор c → потолок r. → { pct, price, drop } (drop — на сколько упадёт ресурс) */
export function repairQuote (c, r) {
  const pct = Math.max(0, Math.round((r - c) * 10) / 10);
  const price = Math.round((BREAK.REPAIR_BASE + BREAK.REPAIR_PER_PCT * pct) / 100) * 100;
  const drop = Math.min(BREAK.CEIL_DROP_MAX, BREAK.CEIL_DROP_MIN + BREAK.CEIL_DROP_PER * pct);
  return { pct, price, drop: Math.round(drop * 10) / 10 };
}

