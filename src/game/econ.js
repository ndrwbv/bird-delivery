  ZONE: { rich: 1.25, normal: 1, poor: 0.85, garage: 0.95, ind: 1, gang: 1.3 },
  URGENT: 2.5,                 // срочный: средняя дальность, мало времени — ×2,5 (было ×1,8); всё про срочный — URGENT ниже
  URGENT_MIN_M: 1800, URGENT_TIME: 0.62,     // только карта без районов (песочница): не ближе 1,8 км, срок 62 % обычного
  EDGE: 1.4,                   // «в конец города»
