/* ──────────────────────────────────────────────────────────────────────────
   Плавное появление вдали (docs/CAREER.md «Город: как выглядит» → «Плавное появление»).

   Раньше мелочь на газоне, кусты ельника и подробные ели появлялись и пропадали
   разом, целой клеткой 40—48 м, на границе своей дальности — «всё слишком резко
   отображается». Теперь граница размыта в шейдере, по расстоянию от камеры до
   каждой вещи (её основания):

     • рост из земли (grow) — вещь в полосе [a, b] м от камеры растёт от нуля
       до полного размера; дальше b её нет (сжата в точку — ничего не рисуется);
     • растворение (dither) — для смены подробной модели на простую: в полосе
       перехода у каждой точки экрана свой порог (узор 4 × 4), подробная модель
       тает точка за точкой, простая на её месте проявляется. Без прозрачности
       и сортировки — столько же стоит, сколько обычная отрисовка.

   uFade = (a, b): полная — ближе a, нет — дальше b. Код меша кладёт вещи до b +
   полклетки, шейдер прячет лишнее — край клетки больше не виден.
   ────────────────────────────────────────────────────────────────────────── */

/* доля 0…1 по расстоянию d: 1 — ближе a, 0 — дальше b */
export const FADE_FN = `
float fadeK (float d, vec2 ab) { return 1.0 - smoothstep(ab.x, ab.y, d); }`;

/* узор Байера 4 × 4: порог точки экрана 0…1 */
export const BAYER_FN = `
float bayer4 (vec2 p) {
  vec2 q = mod(floor(p), 4.0);
  float i = q.x + q.y * 4.0;
  float v = i < 1.0 ? 0.0 : i < 2.0 ? 8.0 : i < 3.0 ? 2.0 : i < 4.0 ? 10.0 :
            i < 5.0 ? 12.0 : i < 6.0 ? 4.0 : i < 7.0 ? 14.0 : i < 8.0 ? 6.0 :
            i < 9.0 ? 3.0 : i < 10.0 ? 11.0 : i < 11.0 ? 1.0 : i < 12.0 ? 9.0 :
            i < 13.0 ? 15.0 : i < 14.0 ? 7.0 : i < 15.0 ? 13.0 : 5.0;
  return (v + 0.5) / 16.0;
}`;

/* основание экземпляра в мире (InstancedMesh) и расстояние до камеры по земле */
export const BASE_DIST = `
  vec3 fadeB0 = (modelMatrix * instanceMatrix * vec4(0.0, 0.0, 0.0, 1.0)).xyz;
  float fadeD = length(fadeB0.xz - cameraPosition.xz);`;

/* рост из земли: transformed — вокруг основания экземпляра (до instanceMatrix — вокруг нуля шаблона) */
export const GROW_BEGIN = `
  transformed *= max(fadeK(fadeD, uFade), 0.0);`;

/* uniform-объект для материала: { uFade: { value: Vector2 } } */
export function uniform (THREE, a, b) { return { value: new THREE.Vector2(a, b) }; }
