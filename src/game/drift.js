/* ──────────────────────────────────────────────────────────────────────────
   Занос и дрифт (12бо, автор 24.10.2026: «добавь занос машины на поворотах и при ручнике, чтобы можно было
   дрифтить… чтобы её заносило немного, а если жать ручник, то сильнее заносить будет»).

   Как устроено. Машина поворачивает носом (руль → курс), а скорость догоняет нос не сразу: боковой снос
   (скорость поперёк кузова) гаснет со скоростью «сцепления» k, 1/с. Угол заноса — между носом и тем, куда
   машина на самом деле едет; в ровном повороте он ≈ скорость поворота / k. Здесь — только это k и предел
   угла на ручнике:
   - без ручника: на скорости в резком повороте сцепление чуть слабее (LOOSE) — зад немного уходит наружу
     и снос держится дольше (но не слабее K_MIN — в дождь как было); медленнее FROM — как было;
   - ручник (поворот на нём, как и раньше, в 1,5 раза круче — game.js): быстрее H_FROM «зад сорван» (d от 0
     до 1 за 1/H_IN с) — сцепление падает до H_SIDE, машину несёт боком; отпустил ручник — зад цепляется
     за 1/REL с; держишь газ и угол больше HOLD — дрифт держится (гаснет за 1/GAS_HOLD с); руль в сторону
     заноса — выправляет (COUNTER); медленнее H_FROM зад не срывается — на месте не крутит;
   - пока зад сорван, угол больше H_MAX не растёт: доворот, который увеличил бы угол, плавно гаснет за SOFT°
     до предела — не разворачивает;
   - газон — сцепление ×GRASS, лёд — ×ICE; дождь и снег — как раньше (WET в game.js), песок — beach.js.
   Правило словами — docs/CAREER.md «Занос и дрифт». Следы (tracks.js) и визг (motor.js) — от того же сноса.
   ────────────────────────────────────────────────────────────────────────── */

export const DRIFT = {
  on: !(typeof location !== 'undefined' && /[?&]olddrift\b/.test(location.search)),   // ?olddrift — по-старому, сравнить
  FROM: 8, FULL: 18,        // м/с: с какой скорости начинает заносить (≈ 30 км/ч) и с какой — в полную силу (≈ 65 км/ч)
  LOOSE: 0.18,              // без ручника: на полной скорости и руле до упора сцепление слабее на столько (0 — как было)…
  K_MIN: 6,                 // 1/с: …но не слабее этого: в ливень (5,5) и так носит — там как было
  H_FROM: 5,                // м/с: ручник на меньшей скорости зад не срывает (≈ 18 км/ч)
  H_IN: 5,                  // 1/с: как быстро срывается зад на ручнике
  H_SIDE: 1.5,              // 1/с: сцепление с сорванным задом (было 2,2 — снос гасился быстрее, но корма не уходила)
  H_MAX: 55,                // °, предел угла с ручником
  REL: 2.5,                 // 1/с: отпустил ручник — зад цепляется
  GAS_HOLD: 0.7,            // 1/с: …а с газом, пока угол больше HOLD, — медленно (дрифт держится)
  HOLD: 12,                 // °
  COUNTER: 6,               // 1/с: руль в сторону заноса — зад цепляется быстро
  SOFT: 8,                  // °: за сколько до предела доворот начинает гаснуть
  GRASS: 0.85, ICE: 0.4,    // ×сцепление на газоне и на льду
};

/* для проверок (__dlv.DRIFT): d — насколько сорван зад, slip — угол заноса сейчас, °; peak — наибольший с clear() */
export const ST = { d: 0, slip: 0, peak: 0 };
const R2D = 180 / Math.PI;
const clamp = (v, a, b) => v < a ? a : v > b ? b : v;
let A = null, gT = 0, grass = 0;
const OUT = { k: 0 };
export function init (api) { A = api; }
export function clear () { ST.peak = 0; }

/* шаг физики. k0 — обычное сцепление (сухо / мокро, у машины своё), sv — руль −1…1, vf / vl — скорость вдоль / поперёк
   кузова, м/с. → OUT: k — сцепление на этот шаг, 1/с */
export function step (V, IN, k0, sv, vf, vl, dt) {
  const air = !!V.air;
  const sp = vf > 0 ? vf : 0;
  // угол заноса со знаком: «+» — нос повёрнут туда же, куда поворот с рулём «+»
  const slip = Math.atan2(-vl, Math.max(1, Math.abs(vf))) * R2D;
  ST.slip = slip; if (sp > 3 && Math.abs(slip) > ST.peak) ST.peak = Math.abs(slip);
  // зад сорван ручником; без ручника — цепляется (с газом и в угле — медленно, контр-рулём — быстро)
  if (IN.hand && !air && sp > DRIFT.H_FROM) ST.d = Math.min(1, ST.d + DRIFT.H_IN * dt);
  else if (ST.d > 0) {
    const counter = sv * slip < -0.15 * Math.abs(slip);
    const r = counter ? DRIFT.COUNTER : IN.gas && Math.abs(slip) > DRIFT.HOLD && sp > DRIFT.FROM && !air ? DRIFT.GAS_HOLD : DRIFT.REL;
    ST.d = Math.max(0, ST.d - r * dt);
  }
  // по чему едем: газон — раз в 0,2 с (поиск дороги не дешёвый), лёд — Томь и пруды зимой
  if ((gT -= dt) <= 0) {
    gT = 0.2;
    let g = 1;
    if (A && A.groundAt && A.groundAt(V.x, V.z) === 1) g = DRIFT.GRASS;
    if (A && A.iceY) { const y = A.iceY(V.x, V.z); if (y !== null && Math.abs(V.y - y) < 0.4) g = DRIFT.ICE; }
    grass = g;
  }
  const spK = clamp((sp - DRIFT.FROM) / (DRIFT.FULL - DRIFT.FROM), 0, 1);
  const loose = 1 - DRIFT.LOOSE * spK * Math.min(1, Math.abs(sv));
  const d = ST.d;
  const kt = Math.max(k0 * loose, Math.min(k0, DRIFT.K_MIN));
  OUT.k = (kt + (DRIFT.H_SIDE - kt) * d) * grass;
  return OUT;
}
/* поворот курса w, рад/с (уже со знаком хода): пока зад сорван, доворот, который увеличил бы угол заноса за предел, плавно гаснет */
export function yaw (w, vf, vl) {
  if (ST.d <= 0 || vf < 1) return w;
  const slip = Math.atan2(-vl, vf) * R2D;
  if (w * slip <= 0) return w;                    // выправляет — не трогаем
  return w * clamp((DRIFT.H_MAX - Math.abs(slip)) / DRIFT.SOFT, 0, 1);
}
export function reset () { ST.d = 0; ST.slip = 0; }
