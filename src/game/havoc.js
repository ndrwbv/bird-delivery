let A = { S: null, adult: false };
const H = { n: {}, other: 0, base: {}, since: 0, gap: 4, clean: 0, shift: 0, last: {}, lastText: '', said: 0 };

export function init (api) { A = { ...A, ...api }; reset(); }
const rnd = (a, b) => a + Math.floor(Math.random() * (b - a + 1));

export function reset () {
  for (const k of KINDS) H.n[k] = 0;
  H.other = 0;
  H.since = 0; H.gap = rnd(HV.GAP[0], HV.GAP[1]); H.clean = 0; H.shift++;
  H.base = counts();
}

export function counts () {
  const S = A.S || {};
  return { ...H.n, people: (S.people || 0) + (S.scoots || 0), stop: S.stops || 0 };
}

export function smash (kind) {
  const k = OF[kind];
  if (k) H.n[k]++; else H.other++;
}
export function carHit (car, hit) {
  if (!car || !(hit > HV.CAR_HIT) || car.havShift === H.shift) return;
  car.havShift = H.shift;
  H.n.car++;
}

export function deliver () {
  H.since++;
  return H.since >= H.gap && !!pick(false);
}

/* что сказать: { kind, n } | { kind: 'mix', list } | { kind: 'clean' } | null; dice — бросать ли шанс «чистой смены» */
function pick (dice) {
  const c = counts(), d = {};
  let act = 0;
  for (const k of KINDS) { d[k] = Math.max(0, c[k] - (H.base[k] || 0)); if (d[k] > 0) act++; }
  if (!act) {
    if (H.since >= HV.CLEAN && !H.clean && (!dice || Math.random() < HV.CLEAN_P)) return { kind: 'clean' };
    return null;
  }
  const ok = KINDS.filter(k => d[k] > 0 && c[k] >= HV.MIN[k]);
  if (!ok.length) return null;
  if (act >= HV.MIX && (!dice || Math.random() < HV.MIX_P)) {
    const top = KINDS.filter(k => c[k] > 0).sort((a, b) => c[b] - c[a]).slice(0, 4);
    return { kind: 'mix', top, c };
  }
  ok.sort((a, b) => d[b] * HV.W[b] - d[a] * HV.W[a]);
  return { kind: ok[0], n: c[ok[0]] };
}

function list (top, c) {
  const w = top.map(k => NOUN[k](c[k]));
  if (w.length < 2) return w[0] || '';
  return t('{a} и {b}', { a: w.slice(0, -1).join(', '), b: w[w.length - 1] });
}

/* фраза — случайная из кучи, не та же, что в прошлый раз в этой куче, и не та же, что последняя вообще */
export function line () {
  const p = pick(true);
  if (!p) return '';
  const pool = LINES[p.kind].concat(A.adult && ADULT_LINES[p.kind] ? ADULT_LINES[p.kind] : []);
  let i = Math.floor(Math.random() * pool.length);
  if (pool.length > 1 && i === H.last[p.kind]) i = (i + 1) % pool.length;
  const arg = p.kind === 'mix' ? list(p.top, p.c) : p.n;
  let s = pool[i](arg);
  if (s === H.lastText && pool.length > 1) { i = (i + 1) % pool.length; s = pool[i](arg); }
  H.last[p.kind] = i; H.lastText = s;
  if (p.kind === 'clean') H.clean = 1;
  H.base = counts(); H.since = 0; H.gap = rnd(HV.GAP[0], HV.GAP[1]); H.said++;
  return s;
}

