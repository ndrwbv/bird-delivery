/* магазин «заехать по пути»: из вывесок города, между пиццерией и домом героя, с наименьшим крюком */
function viaShop (via, x, z) {
  const P = A.pizza ? A.pizza() : null, V = A.V;
  const sx = P ? P.x : V.x, sz = P ? P.z : V.z;
  const direct = Math.hypot(x - sx, z - sz);
  let best = null, bd = Infinity;
  for (const q of (A.shops && A.shops()) || []) {
    if (!via.kinds.includes(q.k)) continue;
    const dp = Math.hypot(q.x - sx, q.z - sz);
    if (dp < HS.VIA_PZ[0] || dp > HS.VIA_PZ[1]) continue;
    if (A.openAt && !A.openAt(q.x, q.z)) continue;
    const hd = Math.hypot(q.x - x, q.z - z);
    if (hd < 40) continue;                                       // у самого подъезда — не «по пути»
    const detour = dp + hd - direct, pref = !!via.prefer && (via.prefer.test(q.n || '') || via.prefer.test(q.n0 || ''));
    if (detour > HS.VIA_DETOUR + (pref ? HS.VIA_PREF : 0)) continue;
    const score = detour - (pref ? HS.VIA_PREF : 0);           // подходящий по названию — даже с крюком побольше
    if (score < bd) { bd = score; best = q; }
  }
  return best;
}

/* ─────────────── для story.js ─────────────── */
function storyOf (H) {
  const def = HEROES.DEFS.find(d => d.id === H.hero);
  return {
    id: H.hero, name: def.name, catFur: H.catFur || 0,
    who: { seed: def.seed, fem: def.fem, look: def.look },
    items: H.chapters[0].items,
    chapters: H.chapters,
    model: () => HEROES.model(H.hero),
    // дом — ближайший к месту героя (запомнили, когда выдали главу), иначе — где он сейчас
    home: () => {
      const p = prog(H.hero);
      if (p.at) return { near: p.at, any: true };
      const h = HEROES.get(H.hero);
      return h && h.place ? { near: [h.x, h.z], any: true } : null;
    },
    ready: (ctx, p, shift) => ready(H, ctx, p, shift),
    decorate: (o, c) => decorate(H, o, c),
    cond: o => condOf(o),
    onDone: (idx, cond) => done(H, idx, cond),
  };
}

/* need.after: [герой, глав] или [[герой, глав], …] — у других героев пройдено столько глав */
const afterOk = af => !af || (Array.isArray(af[0]) ? af : [af]).every(([id, n]) => (prog(id).ch || 0) >= n);

function ready (H, ctx, p, shift) {
  if (!A || !A.CAREER) return false;
  const c = H.chapters[p.ch], need = (c && c.need) || {};
  if (!c) return false;
  if (M.issued === shift) return false;                          // за смену — одна глава героев
  if ((ctx.shiftOrders | 0) < 1) return false;                   // не первым заказом смены
  if (HEROES.HERO.STREET) {
    if ((p.meets || 0) - (p.m0 || 0) < (need.meets || 0)) return false;
    if (p.ch > 0 && shift - (p.last || 0) < (need.shifts || 0)) return false;
  } else if (shift - (p.last || 0) < Math.max(need.meets || 0, need.shifts || 0)) return false;   // героев на улице нет: встреча = смена
  if (!afterOk(need.after)) return false;
  const h = HEROES.get(H.hero);
  if (!h || !h.place || h.down) return false;                    // нет на месте или сбит — подождём
  // дом — у адреса из пула заказов рядом с героем (в открытом районе, не на краю — иначе orders.js не возьмёт)
  const sp = ctx.pickSpot ? ctx.pickSpot({ near: { x: h.x, z: h.z }, r: HS.HOME_R }) : null;
  p.at = sp ? [sp.x, sp.z] : [h.x, h.z];
  M.issued = shift; M.stats.issued++;
  return true;
}

const COND_WHY = {
  time: N_('успей: времени меньше обычного'),
  fragile: N_('хрупкое: не потеряй ни сердца'),
  via: N_('по пути заехать за «{what}» — {shop}'),
  car: N_('приехать на отечественной — Жека проверит'),
};
/* в детской у главы может быть свой магазин «по пути» (kids.via) */
const viaOf = c => (A && !A.ADULT && c.kids && c.kids.via) || c.via;
function decorate (H, o, c) {
  o.heroId = H.hero; o.noGuest = true;
  o.cond = c.cond || null; o.broke = false; o.late = false; o.viaDone = true; o.via = null;
  if (c.cond === 'time') o.timeK = HS.TIME_K;
  else if (c.cond === 'via' && viaOf(c)) {
    const vw = viaOf(c), q = viaShop(vw, o.x, o.z);
    if (q) { o.via = { x: q.x, z: q.z, name: q.n || q.n0 || '', what: t(vw.what) }; o.viaDone = false; o.timeK = HS.VIA_TIME_K; }
    else o.cond = null;                                          // магазина рядом нет — без условия
  }
  if (o.cond) {
    const s = t(COND_WHY[o.cond], o.via ? { what: o.via.what, shop: o.via.name } : {});
    o.why = o.why + ' · ' + s;
    o.condText = s;
  }
}
function condOf (o) {
  if (!o || !o.cond) return 'ok';
  if (o.cond === 'time') return o.late ? 'bad' : 'ok';
  if (o.cond === 'fragile') return o.broke ? 'bad' : 'ok';
  if (o.cond === 'via') return o.viaDone ? 'ok' : 'bad';
  if (o.cond === 'car') { const k = HQ.carKind(); o.carKind = k; return !k || k === 'home' ? 'ok' : 'bad'; }   // у подъезда: на чём приехал
  return 'ok';
}
function done (H, idx, cond) {
  const p = prog(H.hero);
  p.m0 = p.meets || 0; delete p.at;
  if (cond === 'bad') p.bad = (p.bad || 0) + 1;
  STORY.persist();
  M.stats.done++;
  const c = H.chapters[idx];
  if (c && c.bonus) c.bonus(cond);
}

/* ─────────────── встречи и заказ в пути ─────────────── */
function onMeet (h) {
  if (!A || !A.CAREER || A.S.ride || !BY.has(h.id)) return;
  const last = M.met[h.id];
  if (last !== undefined && M.clock - last < HS.MEET_GAP) return;
  M.met[h.id] = M.clock;
  const p = prog(h.id);
  p.meets = (p.meets || 0) + 1;
  STORY.persist();
  M.stats.meets++;
}

function frame (dt, cutOn) {
  if (!A) return;
  M.clock += dt;
  const S = A.S, V = A.V, sp = curSpec();
  // заказ героя идёт: следим за условием
  if (sp !== M.cur) { M.cur = sp; M.hp = S.hp; }
  if (sp && S.state === 'drive') {
    if (sp.cond === 'fragile' && !sp.broke && S.hp < M.hp - 0.01) {
      sp.broke = true; M.stats.broke++;
      if (A.toast) A.toast(t('💥 разбил! {what}', { what: sp.items }));
    }
    if (sp.via && !sp.viaDone && Math.hypot(V.x - sp.via.x, V.z - sp.via.z) < HS.VIA_R && Math.hypot(V.vx, V.vz) * 3.6 < HS.VIA_KMH) {
      sp.viaDone = true; M.stats.via++;
      if (A.toast) A.toast(t('✓ {what} — взял', { what: sp.via.what }));
      if (A.Snd && A.Snd.coin) A.Snd.coin();
    }
  }
  M.hp = S.hp;
  // герой ждёт у двери (или играет в катсцене) — на улице его нет
  const cut = cutOn && STORY.DEBUG.CUT.story ? STORY.DEBUG.CUT.story.id : null;
  const want = cut && BY.has(cut) ? cut : sp ? sp.heroId : null;
  if (want !== M.held) {
    if (M.held) HEROES.hold(M.held, false);
    if (want) HEROES.hold(want, true);
    M.held = want;
  }
}

/** пины на радаре и карте: магазин «заехать по пути» текущего заказа героя */
export function pins () {
  const sp = A && curSpec();
  if (!sp || !sp.via || sp.viaDone || A.S.state !== 'drive') return [];
  return [{ x: sp.via.x, z: sp.via.z }];
}

export function init (api) {
  A = api;
  if (M.ready) return;
  M.ready = true;
  for (const H of HERO_STORIES) STORY.register(storyOf(H));
  HEROES.onMeet(onMeet);
  STORY.onFrame(frame);
  if (typeof window !== 'undefined') window.setTimeout(() => { if (window.__dlv) window.__dlv.HSTORY = DEBUG; }, 0);
}

/** сменили профиль без перезагрузки (game.js reprofile): глава «за смену» и встречи — заново */
export function resetSession () { if (M.held) HEROES.hold(M.held, false); M.issued = -1; M.cur = null; M.held = null; M.met = {}; }

