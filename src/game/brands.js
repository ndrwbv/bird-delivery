const hash = s => { let h = 2166136261; for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619); return h >>> 0; };

/* Переписать вывески на месте. После этого у точки: n — что написано на
   вывеске (уже на языке игры), n0 — настоящее имя из карты, c — цвета */
export function sanitizePois (pois) {
  for (const p of pois) {
    if (p.n0 !== undefined) continue;
    p.n0 = p.n || '';
    const src = [p.b || '', p.n0];
    const hit = CHAINS.find(([re]) => src.some(s => re.test(s)));
    if (hit) { p.n = t(hit[1]); p.c = [hit[2], hit[3]]; }
    else {
      const pool = POOL[p.k] || POOL.shop;
      p.n = t(pool[hash(p.n0 + ':' + p.p[0].toFixed(0) + ':' + p.p[1].toFixed(0)) % pool.length]);
      p.c = KIND_COLORS[p.k] || KIND_COLORS.shop;
    }
    delete p.b;
  }
  return pois;
}

/* Названия зданий из карты (бизнес-центры, префектуры, храмы) в игре не
   показываем, кроме типовых — «бизнес-центр» и т. п. */
export function buildingLabel (n) {
  if (!n) return '';
  if (/бизнес-центр|бц\b/i.test(n)) return t('бизнес-центр');
  if (/тц\b|молл|торгов/i.test(n)) return t('торговый центр');
  if (/храм|церк/i.test(n)) return t('храм');
  if (/школ|колледж|техникум|гимназ/i.test(n)) return t('школа');
  if (/детский сад/i.test(n)) return t('детский сад');
  if (/рынок/i.test(n)) return t('рынок');
  return '';
}
