/* ──────────────────────────────────────────────────────────────────────────
   Одёжки котов и собак зимой (18.10.2026, автор: «Коты и собаки в одеждах»). Правила словами — docs/CAREER.md
   «Люди и звери зимой».

   Зимой (и в первый снег, и в оттепель — пока холодно или лежит снег) домашние звери в одёжке: собаки с хозяином
   (гуляющие во дворах, собачки богатых, собака клиента у двери) — все (PW.HOME), дворовые коты у подвалов —
   часть (PW.CAT: подкармливают и одевают бабки), коты на крышах и бездомные собаки пустырей — без одёжек.
   Одёжка — коробки в той же склейке, что и зверь (цвета вершин), поэтому ни одного нового меша и вызова отрисовки:
     • свитер — туловище в вязаном цветном, белые полоски, высокое горло;
     • попонка — цветная накидка на спину с белой каймой и ремешком под грудью;
     • комбинезон — как свитер, и штанины на лапах (там, где лапы в той же склейке).
   Летом, весной и осенью — без одёжек.
   ────────────────────────────────────────────────────────────────────────── */
import * as SEAS from './seasons.js';

/* HOME / CAT / STRAY — доля одетых зимой: с хозяином, дворовые коты, бездомные; COLD — с какого холода одевают
   (seasons.js warmth: зима 1, оттепель ~0,6—0,7, поздняя осень 0,68), SNOW — или когда лежит снег */
export const PW = { HOME: 1, CAT: 0.35, STRAY: 0, COLD: 0.65, SNOW: 0.3 };
export const COLORS = ['#d9342c', '#2e6fd6', '#f2c230', '#e0609a', '#3fa86a', '#7a4ad0', '#f28a1c', '#4fc8e8', '#e8e2d4'];   // яркие: на чёрном и рыжем звере видно
const KINDS = ['sweater', 'sweater', 'vest', 'suit'];
export const ST = { dressed: 0, bare: 0 };

const dark = hex => '#' + [1, 3, 5].map(i => Math.round(parseInt(hex.slice(i, i + 2), 16) * 0.68).toString(16).padStart(2, '0')).join('');
/** холодно ли сейчас для одёжек */
export const cold = () => SEAS.warmth() >= PW.COLD || SEAS.snowAmt() > PW.SNOW;
/** одёжка зверю: share — доля одетых (PW.HOME / PW.CAT / PW.STRAY); null — без одёжки (не зима или не выпало) */
export function coatFor (share = PW.HOME, kinds = KINDS) {
  if (!cold() || Math.random() >= share) { ST.bare++; return null; }
  ST.dressed++;
  const ci = (Math.random() * COLORS.length) | 0, c = COLORS[ci];
  return { c, d: dark(c), st: c === '#e8e2d4' ? '#d9342c' : '#f4f1ea', k: kinds[(Math.random() * kinds.length) | 0], ci };
}
/** коробки одёжки — в склейку зверя. b(w, h, d, hex, x, y, z) — как у склеек (yardlife.js propMesh, life.js bits);
    B — туловище { w, h, d, y, z } (z — середина, перед — +z); legs — лапы в той же склейке [[x, z, w, yTop, len]] (комбинезон) */
export function wear (b, B, C, legs) {
  if (!C) return;
  const { w, h, d, y, z } = B;
  if (C.k === 'vest') {                                            // попонка: накидка на спину, кайма, ремешок
    b(w + 0.04, h * 0.5, d * 0.8, C.c, 0, y + h * 0.28, z - d * 0.04);
    b(w + 0.046, h * 0.1, d * 0.8 + 0.01, C.st, 0, y + h * 0.04, z - d * 0.04);
    b(w + 0.03, h + 0.03, 0.05, C.d, 0, y, z + d * 0.28);
    return;
  }
  b(w + 0.03, h + 0.03, d * 0.74, C.c, 0, y, z + d * 0.06);       // свитер (и верх комбинезона)
  for (const k of [-0.18, 0.02]) b(w + 0.036, h + 0.036, 0.04, C.st, 0, y, z + d * k);   // полоски
  b(w + 0.05, h * 0.75, 0.08, C.d, 0, y + h * 0.1, z + d * 0.44);  // высокое горло
  if (C.k === 'suit' && legs) for (const [lx, lz, lw, top, len] of legs) b(lw + 0.025, len * 0.6, lw + 0.025, C.c, lx, top - len * 0.3, lz);
}

export const DEBUG = { PW, ST, cold };
